-- A namespace is the durable repository tenant. Personal namespace IDs are
-- identical to existing user IDs, so no existing repository tenant IDs move.
CREATE TABLE namespaces (
    id UUID PRIMARY KEY,
    slug TEXT NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9][a-z0-9_-]{0,62}$'),
    kind TEXT NOT NULL CHECK (kind IN ('user', 'organization')),
    user_id UUID UNIQUE REFERENCES users(id),
    organization_id UUID UNIQUE,
    CHECK ((kind='user' AND user_id=id AND organization_id IS NULL)
        OR (kind='organization' AND organization_id=id AND user_id IS NULL))
);
INSERT INTO namespaces (id, slug, kind, user_id)
SELECT id, username, 'user', id FROM users;

CREATE TABLE organizations (
    id UUID PRIMARY KEY,
    created_by UUID NOT NULL REFERENCES users(id),
    version BIGINT NOT NULL DEFAULT 1 CHECK (version > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);
ALTER TABLE namespaces ADD CONSTRAINT namespaces_organization_id_fkey
    FOREIGN KEY (organization_id) REFERENCES organizations(id);

CREATE OR REPLACE FUNCTION create_personal_namespace() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO namespaces (id, slug, kind, user_id) VALUES (NEW.id, NEW.username, 'user', NEW.id);
    RETURN NEW;
END $$;
CREATE TRIGGER users_personal_namespace AFTER INSERT ON users
FOR EACH ROW EXECUTE FUNCTION create_personal_namespace();

-- Rebind only ownership/tenant FKs. Actor and author FKs continue to users.
DO $$ DECLARE row record; BEGIN
    FOR row IN
        SELECT con.conrelid::regclass AS table_name, con.conname AS constraint_name,
               att.attname AS column_name
        FROM pg_constraint con
        JOIN pg_attribute att ON att.attrelid=con.conrelid AND att.attnum=con.conkey[1]
        WHERE con.contype='f' AND con.confrelid='users'::regclass
          AND array_length(con.conkey, 1)=1 AND att.attname IN ('owner_id', 'tenant_id')
    LOOP
        EXECUTE format('ALTER TABLE %s DROP CONSTRAINT %I', row.table_name, row.constraint_name);
        EXECUTE format('ALTER TABLE %s ADD CONSTRAINT %I FOREIGN KEY (%I) REFERENCES namespaces(id)',
                       row.table_name, row.constraint_name, row.column_name);
    END LOOP;
END $$;

CREATE TABLE organization_memberships (
    organization_id UUID NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
    user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role TEXT NOT NULL CHECK (role IN ('read','triage','write','maintain','admin')),
    version BIGINT NOT NULL DEFAULT 1 CHECK (version > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY (organization_id, user_id)
);
CREATE INDEX organization_memberships_user_idx ON organization_memberships(user_id, organization_id);

CREATE TABLE organization_teams (
    id UUID PRIMARY KEY,
    organization_id UUID NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
    slug TEXT NOT NULL CHECK (slug ~ '^[a-z0-9][a-z0-9_-]{0,62}$'),
    name TEXT NOT NULL CHECK (octet_length(btrim(name)) BETWEEN 1 AND 128),
    role TEXT NOT NULL CHECK (role IN ('read','triage','write','maintain','admin')),
    version BIGINT NOT NULL DEFAULT 1 CHECK (version > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (organization_id, slug), UNIQUE (id, organization_id)
);
CREATE TABLE organization_team_members (
    team_id UUID NOT NULL,
    organization_id UUID NOT NULL,
    user_id UUID NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY (team_id, user_id),
    FOREIGN KEY (team_id, organization_id) REFERENCES organization_teams(id, organization_id) ON DELETE CASCADE,
    FOREIGN KEY (organization_id, user_id) REFERENCES organization_memberships(organization_id, user_id) ON DELETE CASCADE
);
CREATE INDEX organization_team_members_user_idx ON organization_team_members(user_id, organization_id);

CREATE TABLE organization_creation_keys (
    actor_id UUID NOT NULL REFERENCES users(id),
    key TEXT NOT NULL,
    slug TEXT NOT NULL,
    organization_id UUID NOT NULL,
    PRIMARY KEY (actor_id, key)
);
CREATE TABLE organization_audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id UUID NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
    actor_id UUID NOT NULL REFERENCES users(id),
    action TEXT NOT NULL,
    target TEXT NOT NULL,
    details JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX organization_audit_by_org ON organization_audit_log(organization_id, id);

CREATE OR REPLACE FUNCTION protect_last_organization_admin() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.role='admin' AND (TG_OP='DELETE' OR NEW.role<>'admin') THEN
        PERFORM 1 FROM organizations WHERE id=OLD.organization_id FOR UPDATE;
        IF NOT EXISTS (SELECT 1 FROM organization_memberships
                       WHERE organization_id=OLD.organization_id AND user_id<>OLD.user_id AND role='admin') THEN
            RAISE EXCEPTION 'cannot remove last organization administrator' USING ERRCODE='23514';
        END IF;
    END IF;
    IF TG_OP='DELETE' THEN RETURN OLD; END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER organization_last_admin BEFORE DELETE OR UPDATE OF role ON organization_memberships
FOR EACH ROW EXECUTE FUNCTION protect_last_organization_admin();

CREATE OR REPLACE FUNCTION enforce_repository_actor_membership()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE actor_user_id UUID; repo_owner_id UUID;
BEGIN
    IF TG_TABLE_NAME='git_operations' THEN actor_user_id := NEW.actor_id;
    ELSE actor_user_id := NEW.author_id; END IF;
    SELECT owner_id INTO repo_owner_id FROM repositories WHERE id=NEW.repository_id;
    IF repo_owner_id IS NULL THEN
        RAISE EXCEPTION 'repository does not exist' USING ERRCODE='23503';
    END IF;
    IF EXISTS (SELECT 1 FROM namespaces WHERE id=repo_owner_id AND user_id=actor_user_id)
       OR EXISTS (SELECT 1 FROM organization_memberships
                  WHERE organization_id=repo_owner_id AND user_id=actor_user_id)
       OR EXISTS (SELECT 1 FROM repository_collaborators
                  WHERE repository_id=NEW.repository_id AND user_id=actor_user_id)
       OR EXISTS (SELECT 1 FROM repository_team_members
                  WHERE repository_id=NEW.repository_id AND user_id=actor_user_id)
    THEN RETURN NEW; END IF;
    RAISE EXCEPTION 'actor is not a member or collaborator of repository' USING ERRCODE='23514';
END $$;

