def closure(root):
    from pathlib import Path
    base = Path(root).resolve()
    paths = set(INPUT_FILES)
    for pattern in INPUT_GLOBS:
        matches = [path for path in base.glob(pattern) if path.is_file() and not path.is_symlink()]
        if not matches:
            raise ValueError("required native11 input closure is unavailable")
        paths.update(path.relative_to(base).as_posix() for path in matches)
    return sorted(paths)
